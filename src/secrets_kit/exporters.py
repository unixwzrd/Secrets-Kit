"""
secrets_kit.exporters

Export helpers for shell runtime usage.
"""

from __future__ import annotations

import os
import re
import shlex
import stat
from pathlib import Path
from typing import Dict


def write_protected_export(*, destination: Path, payload: bytes) -> None:
    """Atomically publish a new owner-only file, never replacing an existing path.

    The destination directory must already exist and have no symlink components.
    A pinned directory descriptor keeps publication and cleanup in that directory.
    No secret contents are included in exceptions generated by this helper.
    """
    destination = destination.expanduser().absolute()
    parent = destination.parent
    for path in (parent, *parent.parents):
        if path.is_symlink():
            raise ValueError("export_symlink_directory")
    descriptor = os.open(parent, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    temporary = None
    created = False
    try:
        info = os.fstat(descriptor)
        if info.st_uid != os.getuid() or stat.S_IMODE(info.st_mode) & 0o022:
            raise ValueError("export_unsafe_directory")
        # The random name is created relative to the pinned destination directory.
        temporary = ".seckit-export-" + os.urandom(16).hex()
        output = os.open(
            temporary,
            os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW,
            0o600,
            dir_fd=descriptor,
        )
        created = True
        with os.fdopen(output, "wb") as stream:
            stream.write(payload)
            stream.flush()
            os.fsync(stream.fileno())
        os.link(
            temporary,
            destination.name,
            src_dir_fd=descriptor,
            dst_dir_fd=descriptor,
            follow_symlinks=False,
        )
        os.fsync(descriptor)
    finally:
        if created:
            os.unlink(temporary, dir_fd=descriptor)
        os.close(descriptor)


def export_shell_lines(*, env_map: Dict[str, str]) -> str:
    """Render shell export lines with safe quoting."""
    lines = []
    for key in sorted(env_map):
        lines.append(f"export {key}={shlex.quote(env_map[key])}")
    return "\n".join(lines)


def export_dotenv_placeholders(*, keys: list[str]) -> str:
    """Render dotenv placeholders that reference the key name itself."""
    lines = []
    for key in sorted(keys):
        lines.append(f"{key}=${{{key}}}")
    return "\n".join(lines)


def export_dotenv_values(*, env_map: Dict[str, str]) -> str:
    """Render value-bearing dotenv assignments for compatible loaders.

    Reject interpolation and unsupported control characters instead of writing a
    file that could load a different credential value. The caller must publish
    this plaintext through the protected new-file writer.
    """
    escapes = {
        "\\": "\\\\",
        '"': '\\"',
        "\a": "\\a",
        "\b": "\\b",
        "\f": "\\f",
        "\n": "\\n",
        "\r": "\\r",
        "\t": "\\t",
        "\v": "\\v",
    }
    lines = []
    for key in sorted(env_map):
        if re.fullmatch(r"[A-Z0-9_]+", key) is None:
            raise ValueError("dotenv_value_unsupported")
        value = env_map[key]
        try:
            value.encode("utf-8")
        except UnicodeError as exc:
            raise ValueError("dotenv_value_unsupported") from exc
        if "${" in value or any(
            (ord(char) < 32 and char not in escapes) or ord(char) == 127 for char in value
        ):
            raise ValueError("dotenv_value_unsupported")
        # python-dotenv's quoted-value parser mistakes the closing quote for an
        # escaped quote when the value ends in a backslash. Use an unquoted
        # assignment only when that spelling preserves the value exactly.
        if value.endswith("\\"):
            if (
                value[0] in "\"'"
                or value[0].isspace()
                or any(ord(char) < 32 for char in value)
                or re.search(r"\s+#", value)
            ):
                raise ValueError("dotenv_value_unsupported")
            lines.append(f"{key}={value}")
            continue
        encoded = "".join(escapes.get(char, char) for char in value)
        lines.append(f'{key}="{encoded}"')
    return "\n".join(lines)
